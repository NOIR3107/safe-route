"""Builds docs/exp11/test-cases.md from backend/reports/junit.xml and the test source.

Every row is a real test function; the result column is what the last run reported.
Run from the repo root after `pytest --junitxml=reports/junit.xml` in backend/:
    python docs/exp11/gen_cases.py
"""

import ast
import re
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TESTS = ROOT / "backend" / "tests"
JUNIT = ROOT / "backend" / "reports" / "junit.xml"
OUT = Path(__file__).with_name("test-cases.md")

# result per test function (parametrized cases are folded into one row)
runs: dict[str, list[tuple[str, float]]] = defaultdict(list)
suite = ET.parse(JUNIT).getroot()
suite = suite if suite.tag == "testsuite" else suite.find("testsuite")
for case in suite.iter("testcase"):
    name = case.get("name").split("[")[0]
    failed = case.find("failure") is not None or case.find("error") is not None
    skipped = case.find("skipped") is not None
    runs[name].append(("FAIL" if failed else "SKIP" if skipped else "PASS", float(case.get("time", 0))))


def fr_list(text: str) -> list[str]:
    """FR-03, FR-07/08 and FR-01..05 style references, expanded and sorted."""
    found = set()
    for a, rest in re.findall(r"FR-(\d+)((?:(?:/|\.\.|\.\.FR-)\d+)*)", text):
        nums = [int(a)] + [int(n) for n in re.findall(r"\d+", rest)]
        if ".." in rest:
            nums = list(range(nums[0], nums[-1] + 1))
        found.update(nums)
    return [f"FR-{n:02d}" for n in sorted(found)]


def tc_id(fn: str) -> str:
    m = re.match(r"test_([a-z]+)(\d+)", fn)
    return f"TC-{m.group(1).upper()}-{int(m.group(2)):02d}" if m else fn


rows = []
for path in sorted(TESTS.rglob("test_*.py")):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    module_doc = (ast.get_docstring(tree) or "").splitlines()[0]
    frs = ", ".join(fr_list(module_doc)) or "-"
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
            doc = ast.get_docstring(node)
            words = re.sub(r"^test_[a-z]+\d+_", "", node.name).replace("_", " ")
            desc = (doc.splitlines()[0] if doc else words[0].upper() + words[1:])
            res = runs.get(node.name, [])
            status = "NOT RUN" if not res else ("FAIL" if any(r == "FAIL" for r, _ in res) else "PASS")
            cases = len(res)
            rows.append((tc_id(node.name), desc, path.relative_to(ROOT).as_posix(), frs, cases, status))

rows.sort(key=lambda r: r[0])
total = sum(r[4] for r in rows)
passed = sum(r[4] for r in rows if r[5] == "PASS")
lines = [
    "# Backend test cases (generated)",
    "",
    f"Generated by `docs/exp11/gen_cases.py` from `backend/reports/junit.xml`: {len(rows)} test functions, "
    f"{total} executed cases (parametrized cases counted separately), {passed} passed.",
    "",
    "| ID | What it checks | File | FR | Cases | Result |",
    "|---|---|---|---|---:|---|",
]
lines += [f"| {i} | {d} | `{f}` | {fr} | {c} | {s} |" for i, d, f, fr, c, s in rows]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT}: {len(rows)} functions, {total} cases, {passed} passed")
